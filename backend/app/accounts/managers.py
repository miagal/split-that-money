"""Manager for the custom email-based user model."""

from django.contrib.auth.base_user import BaseUserManager


class UserManager(BaseUserManager):
    """Create normal and administrative users using email as login."""

    def create_user(self, email: str, password: str | None = None, **extra_fields):
        """Create a normal user with normalized email and hashed password."""
        if not email:
            raise ValueError("Users must have an email address.")

        user = self.model(email=self.normalize_email(email), **extra_fields)
        user.set_password(password)
        user.save(using=self._db)
        return user

    def create_superuser(self, email: str, password: str | None = None, **extra_fields):
        """Create a staff superuser for instance administration."""
        extra_fields.setdefault("is_staff", True)
        extra_fields.setdefault("is_superuser", True)
        extra_fields.setdefault("is_active", True)

        if extra_fields.get("is_staff") is not True:
            raise ValueError("Superusers must have is_staff=True.")
        if extra_fields.get("is_superuser") is not True:
            raise ValueError("Superusers must have is_superuser=True.")

        return self.create_user(email, password, **extra_fields)
